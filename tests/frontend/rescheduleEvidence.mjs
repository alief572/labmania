import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { parse, compileScript } from '@vue/compiler-sfc';
import ts from 'typescript';
import { createRenderer } from 'vue';
const file = new URL('../../resources/js/pages/Sales/Reschedule.vue', import.meta.url);
const source = readFileSync(file, 'utf8');
let code = ts.transpileModule(compileScript(parse(source).descriptor, { id: 'reschedule-evidence' }).content, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText;
code = code.replace(/import (\w+) from ['"][^'"]+\.vue['"];?/g, (_, symbol) => `const ${symbol}={};`);
code = code.replace(/import \{ useConfirmedMutation \} from [^;]+;/, 'const useConfirmedMutation = () => ({ pending: ref(false) });');
code = code.replace(/from (['"])([^'"]+)\1/g, (_, quote, path) => `from '${path.startsWith('.') ? new URL(path + '.ts', file).href : import.meta.resolve(path)}'`);
const component = (await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`)).default;
component.render = () => null;
const renderer = createRenderer({ patchProp() {}, insert() {}, remove() {}, createElement: () => ({}), createText: () => ({}), createComment: () => ({}), setText() {}, setElementText() {}, parentNode: () => null, nextSibling: () => null });
const historicalFile = { id: 9, nama_file: 'Evidence historis.png' };
const history = [{ id: 1, evidence: [historicalFile] }];
const app = renderer.createApp(component, { program: { id: 1, tgl_mulai: '2026-12-01', tgl_selesai: '2026-12-03', durasi_hari: 3 }, history, version: 'v1', requestId: 'request', reason: null, canManage: true, minimum: '2026-11-28', trainers: [], assistants: [], impact: {} });
const s = app.mount({}).$.setupState;
const a = new File(['pdf'], 'PO.pdf'), b = new File(['png'], 'Bukti.png');
const input = { files: [a, b], value: 'chosen' };
s.addEvidence({ target: input });
assert.equal(input.value, ''); assert.deepEqual(s.form.evidence, [a, b]);
s.removeEvidence(0); assert.deepEqual(s.form.data().evidence, [b]);
input.files = [a]; s.addEvidence({ target: input });
assert.deepEqual(s.form.evidence, [b, a]);
s.form.processing = true; s.removeEvidence(0); s.addEvidence({ target: { files: [a], value: 'busy' } });
assert.deepEqual(s.form.evidence, [b, a]);
s.form.processing = false; s.confirming = true; s.removeEvidence(0);
assert.equal(s.form.evidence.length, 2);
s.confirming = false; s.removeEvidence(1); s.removeEvidence(0);
assert.equal(s.form.data().evidence.length, 0);
s.addEvidence({ target: input }); assert.deepEqual(s.form.evidence, [a]);
assert.deepEqual(history[0].evidence, [historicalFile]);
app.unmount();
assert.match(source, /:required="!form.evidence.length"/);
assert.match(source, /<ul v-if="h.evidence.length" class="rs-history-evidence"><li v-for=/);
console.log('Reschedule evidence: tambah/hapus/pilih ulang, payload, busy guard dan riwayat tetap lulus.');
