import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { parse, compileScript } from '@vue/compiler-sfc';
import ts from 'typescript';
import { createRenderer } from 'vue';
const file = new URL('../../resources/js/components/QuotationParticipants.vue', import.meta.url);
const source = readFileSync(file, 'utf8');
let code = ts.transpileModule(compileScript(parse(source).descriptor, { id: 'participants-tab' }).content, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText;
code = code.replace(/import (\w+) from ['"][^'"]+\.vue['"];?/g, (_, name) => `const ${name}={};`);
code = code.replace(/import \{ useConfirmedMutation \} from [^;]+;/, 'const useConfirmedMutation = () => ({ pending: false });');
code = code.replace(/import \{ useForm, usePage \} from [^;]+;/, `import { useForm } from '${import.meta.resolve('@inertiajs/vue3')}'; const usePage = () => ({ props: { permissions: {} } });`);
code = code.replace(/from (['"])([^'"]+)\1/g, (_, quote, path) => `from '${path.startsWith('.') ? new URL(path + '.ts', file).href : import.meta.resolve(path)}'`);
const component = (await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`)).default;
component.render = () => null;
const renderer = createRenderer({ patchProp() {}, insert() {}, remove() {}, createElement: () => ({}), createText: () => ({}), createComment: () => ({}), setText() {}, setElementText() {}, parentNode: () => null, nextSibling: () => null });
const rows = [ { id: 1, nama: 'Satu', status: 'deal' }, { id: 2, nama: 'Dua', status: 'menunggu' }, { id: 3, nama: 'Tiga', status: 'batal' }, { id: 4, nama: 'Empat', status: 'keluar' } ];
const app = renderer.createApp(component, { rows, manage: true, detail: true, statusFilter: true, dataUrl: '/quotation/batch/1/data', filters: { id_quotation: 3, data: 1, peserta_status: 'all' } });
const s = app.mount({}).$.setupState;
assert.deepEqual(s.statusTabs.map(x => x[2]), [4, 1, 1, 1, 1]);
s.status = 'batal';
assert.equal(s.serverFilters.peserta_status, 'batal');
assert.equal(s.serverFilters.id_quotation, 3);
assert.equal(s.serverFilters.data, 1);
s.status = ''; assert.equal(s.serverFilters.peserta_status, 'all');
assert.equal(s.tableColumns.length, 8);
assert.equal(s.tableColumns[4].visible, false);
assert.equal(s.tableColumns[5].title, 'Masuk lewat');
assert.equal(s.tableColumns[6].title, 'Status');
assert.equal(s.tableColumns[7].title, 'Aksi');
app.unmount();
const batch = renderer.createApp(component, { rows, manage: false });
const b = batch.mount({}).$.setupState;
assert.equal(b.tableColumns[4].visible, true);
assert.equal(b.tableColumns[7].title, 'Action');
batch.unmount();
const page = readFileSync(new URL('../../resources/js/pages/Quotation/Form.vue', import.meta.url), 'utf8');
const dataTab = page.slice(page.indexOf('<template v-if="dataTab">'), page.indexOf('<template v-else>', page.indexOf('<template v-if="dataTab">')));
assert.match(dataTab, /v-if="!peserta.length"/);
assert.match(dataTab, /Belum ada calon peserta yang mengisi/);
assert.match(dataTab, /@click="copyLink"/);
assert.doesNotMatch(dataTab, /Link Konfirmasi Kehadiran<\/h2>|Unduh Excel/);
assert.match(source, /detail \? query : filters\?\.q/);
assert.match(source, /<ActionMenu>/);
console.log('Quotation Data Peserta: kosong, status/count, scope quotation, indeks sort dan mode batch lulus.');
