import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { parse, compileScript } from '@vue/compiler-sfc';
import ts from 'typescript';
import { createRenderer, h, nextTick, ref } from 'vue';
const file = new URL('../../resources/js/components/DocumentUpload.vue', import.meta.url);
let code = ts.transpileModule(compileScript(parse(readFileSync(file, 'utf8')).descriptor, { id: 'upload-test' }).content, { compilerOptions: { module: ts.ModuleKind.ES2022, target: ts.ScriptTarget.ES2022 } }).outputText;
code = code.replace(/from ['"]vue['"]/g, `from '${import.meta.resolve('vue')}'`);
const component = (await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`)).default;
component.render = () => null;
const renderer = createRenderer({ patchProp() {}, insert() {}, remove() {}, createElement: () => ({}), createText: () => ({}), createComment: () => ({}), setText() {}, setElementText() {}, parentNode: () => null, nextSibling: () => null });
const oldDocument = globalThis.document;
const listeners = new Map();
globalThis.document = { addEventListener: (event, listener) => listeners.set(event, listener), removeEventListener: (event, listener) => { assert.equal(listeners.get(event), listener); listeners.delete(event); } };
const selected = ref([]), disabled = ref(false);
const app = renderer.createApp({ setup: () => () => h(component, { modelValue: selected.value, disabled: disabled.value, 'onUpdate:modelValue': files => { selected.value = files; } }) });
const upload = (name, size = 10) => new File([new Uint8Array(size)], name);
try {
    const root = app.mount({});
    const s = root.$.subTree.component.setupState;
    const input = { files: [upload('PO.pdf'), upload('SPK.docx')], value: 'selected' };
    s.choose({ target: input }); await nextTick();
    assert.equal(input.value, ''); assert.equal(selected.value.length, 2);
    let stopped = false;
    s.drop({ preventDefault: () => { stopped = true; }, dataTransfer: { files: [upload('Biaya.xlsx')] } }); await nextTick();
    assert.equal(stopped, true); assert.equal(selected.value.length, 3);
    stopped = false;
    listeners.get('paste')({ preventDefault: () => { stopped = true; }, clipboardData: { files: [], items: [] } });
    assert.equal(stopped, false, 'paste teks tidak dicegat');
    listeners.get('paste')({ preventDefault: () => { stopped = true; }, clipboardData: { files: [upload('image.png')], items: [] } }); await nextTick();
    assert.equal(stopped, true); assert.equal(selected.value.length, 4);
    listeners.get('paste')({ preventDefault() {}, clipboardData: { files: [], items: [{ kind: 'file', getAsFile: () => upload('Bukti.jpg') }] } }); await nextTick();
    assert.equal(selected.value.length, 5);
    s.add([upload('script.exe'), upload('besar.pdf', 5 * 1024 * 1024 + 1), upload('kosong.pdf', 0)]); await nextTick();
    assert.equal(selected.value.length, 5); assert.equal(s.errors.length, 3);
    s.add(Array.from({ length: 16 }, (_, i) => upload(`dokumen-${i}.pdf`))); await nextTick();
    assert.equal(selected.value.length, 20); assert.match(s.errors[0], /20 berkas/);
    selected.value = selected.value.slice(1); await nextTick();
    assert.equal(selected.value.length, 19);
    disabled.value = true; await nextTick();
    s.add([upload('no.pdf')]); s.paste({ clipboardData: { files: [upload('no.png')] }, preventDefault: () => assert.fail('paste disabled') }); await nextTick();
    assert.equal(selected.value.length, 19);
    app.unmount(); assert.equal(listeners.has('paste'), false);
} finally { globalThis.document = oldDocument; }
const form = readFileSync(new URL('../../resources/js/pages/Quotation/Form.vue', import.meta.url), 'utf8');
const modal = form.slice(form.indexOf('<ConfirmDialog v-if="[\'deal\', \'dokumen\']'));
assert.match(modal, /size="wide"/);
assert.match(modal, /class="ps-row"/);
assert.ok(modal.indexOf('<DocumentUpload') < modal.indexOf('class="deal-note"'));
console.log('Upload dokumen: multi pilih/drop/paste, teks tetap, batas format/ukuran/jumlah, disabled dan cleanup lulus.');
